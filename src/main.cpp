// Disposition par défaut du bandeau de 24 LEDs :
//   LED 0-3   : 4 voyants à gauche
//   LED 4-19  : 16 LEDs de shift light au centre (vert aux extrémités, rouge, bleu au milieu)
//   LED 20-23 : 4 voyants à droite
// Rôles : 0 shift vert, 1 shift rouge, 2 shift bleu, 3 cligno gauche, 4 cligno droit, 5 temp. eau,
//         6 huile, 7 WiFi, 8 feux de croisement, 9 essence, 11 feux de route
void ledParDefaut(int i, uint8_t &role, uint32_t &couleur) {
  static const uint8_t ROLES[NUM_LEDS] = {
    3, 6, 10, 5,
    0, 0, 0, 0, 1, 1, 1, 2, 2, 1, 1, 1, 0, 0, 0, 0,
    9, 8, 11, 4
  };
  role = ROLES[i];
  switch (role) {
    case 0:  couleur = 0x00FF00; break;
    case 1:  couleur = 0xFF0000; break;
    case 2:  couleur = 0x0000FF; break;
    case 3:
    case 4:  couleur = 0xFFA500; break;
    case 5:
    case 6:
    case 7:  couleur = 0x00FFFF; break;
    case 8:  couleur = 0x00FF00; break;     // feux de croisement
    case 11: couleur = 0x0000FF; break;     // feux de route
    case 9:  couleur = 0xFFA500; break;
    default: couleur = 0x00FF00; break;
  }
}

// Par défaut : clignotants, alerte eau et huile clignotent ; les autres voyants sont fixes
bool blinkParDefaut(uint8_t role) {
  return (role == 3 || role == 4 || role == 5 || role == 6);
}

