// Calibration du gyroscope : moyenne de 100 mesures, voiture à l'arrêt sur sol plat
void calibrerGyro() {
  if (!mpuOk) return;
  float sx = 0.0f, sy = 0.0f;
  int n = 0;
  for (int k = 0; k < 100; k++) {
    sensors_event_t a, g, t;
    if (mpu.getEvent(&a, &g, &t)) {
      sx += a.acceleration.x;
      sy += a.acceleration.y;
      n++;
    }
    delay(5);
  }
  if (n > 0) {
    offsetX = sx / n;
    offsetY = sy / n;
    sauvegarderConfigGenerale();
  }
}

