// Heure d'été UE : dernier dimanche de mars 01:00 UTC -> dernier dimanche d'octobre 01:00 UTC
int jourSemaineGPS(int a, int m, int j) {      // 0 = dimanche
  static const int t[12] = {0, 3, 2, 5, 0, 3, 5, 1, 4, 6, 2, 4};
  if (m < 3) a--;
  return (a + a / 4 - a / 100 + a / 400 + t[m - 1] + j) % 7;
}

void synchroniserHorloge() {
  if (!(gps.time.isValid() && gps.time.isUpdated() && gps.date.isValid())) return;
  int a = gps.date.year(), mo = gps.date.month(), j = gps.date.day();
  if (a < 2024) return;
  int dimMars = 31 - jourSemaineGPS(a, 3, 31);
  int dimOct  = 31 - jourSemaineGPS(a, 10, 31);
  long cle   = ((long)mo * 100 + j) * 100 + gps.time.hour();
  long debut = ((long)3 * 100 + dimMars) * 100 + 1;
  long fin   = ((long)10 * 100 + dimOct) * 100 + 1;
  int decalage = (cle >= debut && cle < fin) ? 2 : 1;       // UTC+2 l'été, UTC+1 l'hiver
  long sec = (long)gps.time.hour() * 3600L + gps.time.minute() * 60L + gps.time.second();
  horlogeBaseSec = (sec + decalage * 3600L) % 86400L;
  horlogeBaseMs = millis();
  horlogeSynchro = true;
}

long horlogeSecondes() {
  return (horlogeBaseSec + (long)((millis() - horlogeBaseMs) / 1000UL)) % 86400L;
}

// Clé de changement : minute affichée + état des deux-points (clignotent chaque seconde)
int horlogeCle() {
  if (!horlogeSynchro) return 0;
  long s = horlogeSecondes();
  return 1 + (int)(s / 60) * 2 + (int)(s % 2);
}

