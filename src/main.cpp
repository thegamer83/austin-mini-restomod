// ==========================================
// MODE DEMO : simulation d'un cycle de conduite (36 s en boucle)
// ==========================================
void simulerDemo() {
  static unsigned long dernierMs = 0;
  unsigned long ms = millis();
  float dt = (dernierMs == 0) ? 0.0f : (ms - dernierMs) / 1000.0f;
  if (dt > 0.5f) dt = 0.0f;     // reprise après une pause du mode démo
  dernierMs = ms;

  const float CYCLE = 36.0f;
  float t = fmodf(ms / 1000.0f, CYCLE);

  // Vitesse : ralenti, accélération 0->120, décélération 120->0, ralenti
  float vit, acc;
  if (t < 2.0f)        { vit = 0.0f;                          acc = 0.0f;  }
  else if (t < 22.0f)  { vit = (t - 2.0f) * 6.0f;             acc = 0.35f; }
  else if (t < 34.0f)  { vit = 120.0f - (t - 22.0f) * 10.0f;  acc = -0.45f; }
  else                 { vit = 0.0f;                          acc = 0.0f;  }
  vitesseGpsKmph = vit;

  // Rapport et régime selon la vitesse
  const float bas[4]  = {0.0f, 25.0f, 50.0f, 80.0f};
  const float haut[4] = {25.0f, 50.0f, 80.0f, 125.0f};
  int rapport = 0;
  if (vit > 3.0f) {
    rapport = 1;
    for (int g = 3; g >= 0; g--) {
      if (vit >= bas[g]) { rapport = g + 1; break; }
    }
    float f = (vit - bas[rapport - 1]) / (haut[rapport - 1] - bas[rapport - 1]);
    rpmBrut = 2000 + (unsigned int)(f * 5600.0f);
  } else {
    rpmBrut = 900 + (unsigned int)(60.0f * sinf(t * 9.0f)) + (t < 2.0f ? 0 : 0);
  }
  rapportEngage = rapport;

  // Température d'eau : monte lentement, dépasse 100 °C en fin de cycle (test alerte)
  tempEau = 75.0f + 33.0f * (0.5f + 0.5f * sinf(t * 2.0f * PI / CYCLE - 1.2f));

  // Essence : descend de 100 % à 10 % en 3 cycles puis repart
  float cyc = fmodf(ms / 1000.0f, CYCLE * 3.0f) / (CYCLE * 3.0f);
  niveauEssence = 100.0f - 90.0f * cyc;

  // Voyants
  etatAlerteHuile    = (t < 2.0f);                 // pression d'huile basse au démarrage
  vBatterie = (t < 2.0f) ? 11.7f : 14.0f + 0.3f * sinf(t * 0.5f);   // batterie : basse au démarrage, puis charge
  feuxActifs         = (t > 1.0f);
  clignotantGauche   = (t > 4.0f && t < 10.0f);
  clignotantDroit    = (t > 14.0f && t < 20.0f);
  pleinsPharesActifs = (t > 24.0f && t < 30.0f);

  // Forces G
  gLong = acc;
  gLat  = (vit > 3.0f) ? 0.6f * sinf(t * 0.9f) : 0.0f;

  // Compteurs (en RAM seulement)
  double d = (vit / 3600.0f) * dt;
  kilometrageTotal += d;
  tripPartiel += d;

  gpsOk = true;

  // Horloge fictive en démo : 08:30 au démarrage
  if (!horlogeSynchro) {
    horlogeBaseSec = 8L * 3600L + 30L * 60L;
    horlogeBaseMs = millis();
    horlogeSynchro = true;
  }
}

// ==========================================
// CALCUL DU RAPPORT ENGAGÉ (régime + vitesse GPS + rapports de boîte)
// ==========================================
void calculerRapportEngage() {
  static int candidat = -1;
  static unsigned long debutCandidat = 0;

  float vit = vitesseGpsKmph;
  int nouveau;

  if (vit < 3.0f || rpmBrut < 300) {
    nouveau = 0;                                   // quasi à l'arrêt => point mort
    ratioMesure = 0.0f;
  } else {
    // ratio total = régime x circonférence(m) x 60 / (1000 x vitesse)
    ratioMesure = ((float)rpmBrut * (circRoueMm / 1000.0f) * 0.06f) / vit;
    int meilleur = -1;
    float meilleurEcart = 1e9f;
    for (int g = 0; g < 4; g++) {
      float ratioG = ratioBoite[g] * ratioPont;
      float ecart = fabsf(ratioMesure / ratioG - 1.0f);
      if (ecart < meilleurEcart) { meilleurEcart = ecart; meilleur = g + 1; }
    }
    // Écart trop grand (embrayage, patinage, vitesse GPS en retard) : on garde le rapport actuel
    nouveau = (meilleurEcart < 0.20f) ? meilleur : -1;
  }

  if (nouveau < 0) { candidat = -1; return; }

  if (nouveau != candidat) {
    candidat = nouveau;
    debutCandidat = millis();
  } else if (nouveau != rapportEngage && millis() - debutCandidat >= 400) {
    rapportEngage = nouveau;                       // stable depuis 400 ms => on valide
  }
}

// ==========================================
// LOOP
// ==========================================
void loop() {
  if (wifiApActif) {
    server.handleClient();
  }

  while (gpsSerial.available() > 0) {
    char c = gpsSerial.read();
    gps.encode(c);
    dernierOctetGpsRecu = millis();
  }

  if (millis() - dernierOctetGpsRecu < 3000) {
    gpsOk = true;
  } else {
    gpsOk = false;
  }

  if (gps.speed.isUpdated()) {
    vitesseGpsKmph = gps.speed.kmph();
  }

  if (!modeDemo) synchroniserHorloge();

  if (!modeDemo) mettreAJourOdometre();

  etatAlerteHuile    = (digitalRead(PIN_OIL) == LOW);
  clignotantGauche   = (digitalRead(PIN_IND_L) == LOW);
  clignotantDroit    = (digitalRead(PIN_IND_R) == LOW);
  feuxActifs         = (digitalRead(PIN_LIGHTS) == LOW);
  pleinsPharesActifs = (digitalRead(PIN_HIGH_BEAM) == LOW);
  
  int rawTemp = analogRead(PIN_TEMP);
  float tempInstantane = (rawTemp / 4095.0f) * 120.0f; 
  tempEau = (tempEau * 0.9f) + (tempInstantane * 0.1f);

  int rawFuel = analogRead(PIN_FUEL);
  float fuelInstantane = (rawFuel / 4095.0f) * 100.0f;
  niveauEssence = (niveauEssence * 0.9f) + (fuelInstantane * 0.1f);

  float vLue = (analogReadMilliVolts(PIN_VBAT) / 1000.0f) * vbatFacteur;
  vBatterie = (vBatterie < 1.0f) ? vLue : (vBatterie * 0.95f + vLue * 0.05f);

  if (micros() - derniereInterruptionRPM > 1000000) {
    rpmBrut = 0;
  }

  if (rpmBrut > 0) { dernierRpmVuMs = millis(); moteurCoupe = false; }
  else if (millis() - dernierRpmVuMs > 2000) moteurCoupe = true;

  if (!modeDemo) calculerRapportEngage();

  sensors_event_t a, g, tempMpu;
  if (mpuOk && mpu.getEvent(&a, &g, &tempMpu)) {
    gLat = (a.acceleration.x - offsetX) / 9.80665f;
    gLong = (a.acceleration.y - offsetY) / 9.80665f;
  }

  if (modeDemo) simulerDemo();
  if (!modeDemo) gererJournalTrajet();
  gererPerformance();
  gererLuminosite();

  // Alerte surchauffe moteur : se déclenche au-dessus du seuil, se réarme 3 °C en dessous
  if (!alerteTempActive && !alerteTempAcquittee && tempEau > seuilSurchauffe) {
    alerteTempActive = true;
    alerteRedessiner = true;
  }
  if (tempEau < seuilSurchauffe - 3) {
    alerteTempAcquittee = false;
    if (alerteTempActive) {
      alerteTempActive = false;
      dernierePageAffichee = -1;          // redessine la page
    }
  }

  static unsigned long tempsAppuiBtn = 0;
  static bool boutonEnCours = false;
  bool etatBtn = digitalRead(PIN_PAGE_BTN);

  if (etatBtn == LOW && !boutonEnCours) {
    boutonEnCours = true;
    tempsAppuiBtn = millis();
  } 
  else if (etatBtn == HIGH && boutonEnCours) {
    unsigned long dureeAppui = millis() - tempsAppuiBtn;
    boutonEnCours = false;

    if (dureeAppui >= 2000) {
      tripPartiel = 0.0;          // appui long : trip partiel + performances remis à zéro
      sauvegarderOdometre();
      effacerRecords();
      if (pageActuelle == 4) {
        dessinerFondPage3();
      }
    } else if (dureeAppui > 40) {
      if (alerteTempActive) {              // un appui acquitte l'alerte de surchauffe
        alerteTempActive = false;
        alerteTempAcquittee = true;
        dernierePageAffichee = -1;
      } else {
        pageActuelle++;
        if (pageActuelle > 4) pageActuelle = 1;
      }
    }
  }

  static bool etatPrecedentWifiBtn = HIGH;
  bool etatWifiBtn = digitalRead(PIN_WIFI_BTN);
  if (etatWifiBtn == LOW && etatPrecedentWifiBtn == HIGH) {
    delay(40);
    if (!wifiApActif) {
      demarrerWiFiAP();
    } else {
      arreterWiFiAP();
    }
  }
  etatPrecedentWifiBtn = etatWifiBtn;

  if (pageActuelle != dernierePageAffichee) {
    switch (pageActuelle) {
      case 1: dessinerFondPage1(); break;
      case 2: dessinerFondPage2(); break;
      case 3: dessinerFondPage4(); break;      // page 3 = performance
      case 4: dessinerFondPage3(); break;      // page 4 = réglages / système
    }
    dernierePageAffichee = pageActuelle;
  }

  gererBandeauLEDs();

  static unsigned long dernierRafraichissement = 0;
  if (millis() - dernierRafraichissement > 100) {
    switch (pageActuelle) {
      case 1: actualiserPage1(); break;
      case 2: actualiserPage2(); break;
      case 3: actualiserPage4(); break;
      case 4: actualiserPage3(); break;
    }
    if (alerteTempActive) afficherAlerteSurchauffe();     // par-dessus la page, redessiné après chaque mise à jour
    dernierRafraichissement = millis();
  }
}
