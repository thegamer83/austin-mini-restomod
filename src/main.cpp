// Dessine la Mini avec son coin haut-gauche en (ox, 0). La route défile sous les roues.
void dessinerMiniSprite(TFT_eSprite &sp, int ox, float defilement, bool phares) {
  sp.fillSprite(0);
  const int octetsParLigne = MINI_W / 8;
  for (int y = 0; y < MINI_H; y++) {
    int runDebut = -1;
    for (int x = 0; x <= MINI_W; x++) {
      bool allume = false;
      if (x < MINI_W) allume = (pgm_read_byte(&MINI_BMP[y * octetsParLigne + (x >> 3)]) & (0x80 >> (x & 7))) != 0;
      if (allume && runDebut < 0) runDebut = x;
      if (!allume && runDebut >= 0) {
        int a = ox + runDebut, b = ox + x - 1;           // pixels écran du segment
        if (b >= 0 && a < ANIM_W) {
          if (a < 0) a = 0;
          if (b > ANIM_W - 1) b = ANIM_W - 1;
          sp.drawFastHLine(a, y, b - a + 1, 1);
        }
        runDebut = -1;
      }
    }
  }

  // Route avec traits qui défilent vers la droite (la voiture avance vers la gauche)
  const int yRoute = MINI_H;
  sp.drawFastHLine(0, yRoute, ANIM_W, 1);
  int dec = (int)defilement % 60;
  for (int x = -60 + dec; x < ANIM_W; x += 60) {
    int a = x, b = x + 24;
    if (b < 0 || a >= ANIM_W) continue;
    if (a < 0) a = 0;
    if (b > ANIM_W - 1) b = ANIM_W - 1;
    sp.drawFastHLine(a, yRoute + 6, b - a + 1, 1);
  }

  // Faisceau du phare, une fois arrêtée
  if (phares) {
    for (int k = -2; k <= 2; k++) sp.drawLine(ox + 4, 80, 0, 80 + k * 26, 1);
  }
}

