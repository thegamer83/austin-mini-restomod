// Garde les 60 derniers trajets quand le fichier devient trop gros
void limiterJournal() {
  fs::File f = LittleFS.open(FICHIER_JOURNAL, "r");
  if (!f) return;
  if (f.size() < 12000) { f.close(); return; }
  String lignes[60];
  int total = 0;
  while (f.available()) {
    String l = f.readStringUntil('\n');
    l.trim();
    if (l.length() < 5 || l.startsWith("date")) continue;
    lignes[total % 60] = l;
    total++;
  }
  f.close();
  fs::File g = LittleFS.open(FICHIER_JOURNAL, "w");
  if (!g) return;
  g.print(String(ENTETE_JOURNAL) + "\n");
  int nb = (total < 60) ? total : 60;
  int debut = total - nb;
  for (int k = 0; k < nb; k++) g.print(lignes[(debut + k) % 60] + "\n");
  g.close();
}

void ajouterLigneJournal(const String &ligne) {
  if (!fsOk) return;
  bool existe = LittleFS.exists(FICHIER_JOURNAL);
  fs::File f = LittleFS.open(FICHIER_JOURNAL, "a");
  if (!f) return;
  if (!existe) f.print(String(ENTETE_JOURNAL) + "\n");
  f.print(ligne + "\n");
  f.close();
  limiterJournal();
}

// Tableau HTML des 8 derniers trajets
String journalHtml() {
  if (!fsOk || !LittleFS.exists(FICHIER_JOURNAL)) return "<p>Aucun trajet enregistre.</p>";
  fs::File f = LittleFS.open(FICHIER_JOURNAL, "r");
  if (!f) return "<p>Journal illisible.</p>";
  String derniers[8];
  int total = 0;
  while (f.available()) {
    String l = f.readStringUntil('\n');
    l.trim();
    if (l.length() < 5 || l.startsWith("date")) continue;
    derniers[total % 8] = l;
    total++;
  }
  f.close();
  if (total == 0) return "<p>Aucun trajet enregistre.</p>";

  String html = "<p style='font-size:12px;color:#aaa;'>" + String(total) + " trajet(s) dans le journal. Les 8 derniers :</p>";
  html += "<table style='font-size:12px;width:100%;text-align:center;'><tr style='color:#aaa;'><td>Date</td><td>Debut</td><td>Min</td><td>Km</td><td>Vmax</td><td>Vmoy</td><td>Eau</td></tr>";
  int nb = (total < 8) ? total : 8;
  for (int k = 0; k < nb; k++) {
    String l = derniers[(total - 1 - k) % 8];
    html += "<tr>";
    int pos = 0;
    for (int c = 0; c < 7; c++) {
      int idx = l.indexOf(';', pos);
      String champ = (idx < 0) ? l.substring(pos) : l.substring(pos, idx);
      html += "<td>" + champ + "</td>";
      if (idx < 0) break;
      pos = idx + 1;
    }
    html += "</tr>";
  }
  html += "</table>";
  return html;
}

