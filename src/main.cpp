void tracerAiguille(const Aiguille &a, float angleDeg, uint16_t col) {
  float rad = angleDeg * DEG2RAD_F;
  float ca = cosf(rad), sa = sinf(rad);
  float px = -sa * a.demiLargeur;
  float py =  ca * a.demiLargeur;
  int tx = a.cx + (int)(a.longueur * ca);
  int ty = a.cy + (int)(a.longueur * sa);
  int qx = a.cx - (int)(a.longueur * 0.18f * ca);
  int qy = a.cy - (int)(a.longueur * 0.18f * sa);
  int b1x = a.cx + (int)px, b1y = a.cy + (int)py;
  int b2x = a.cx - (int)px, b2y = a.cy - (int)py;
  tft.fillTriangle(tx, ty, b1x, b1y, b2x, b2y, col);
  tft.fillTriangle(qx, qy, b1x, b1y, b2x, b2y, col);
}

// Efface l'ancienne aiguille (couleur du cadran) et trace la nouvelle. Retourne true si elle a bougé.
bool deplacerAiguille(Aiguille &a, float nouvelAngle) {
  bool dejaTracee = (a.angle > -900.0f);
  if (dejaTracee && fabsf(nouvelAngle - a.angle) < 0.8f) return false;
  if (dejaTracee) tracerAiguille(a, a.angle, COUL_CADRAN);
  tracerAiguille(a, nouvelAngle, a.couleur);
  a.angle = nouvelAngle;
  return true;
}

