void gererBandeauLEDs() {
  FastLED.clear();
  FastLED.setBrightness(modeNuit ? (uint8_t)((luminositeLeds * lumNuit) / 255) : luminositeLeds);

  bool seuilMaxAtteint = (rpmBrut >= seuilRpmMax);
  bool phaseRapide = (millis() / 150) % 2 == 0;     // alertes
  bool phaseCligno = (millis() / 250) % 2 == 0;     // clignotants

  for (int i = 0; i < NUM_LEDS; i++) {
    uint8_t role = roleLeds[i];
    uint32_t col = couleurLeds[i];

    // Shift light (rôles 0, 1, 2) : au RPM max, TOUTES ces LEDs clignotent
    if (role <= 2) {
      if (rpmBrut >= rpmMinShift) {
        if (seuilMaxAtteint) {
          if (phaseRapide) leds[i] = col;
        } else if ((role == 0 && rpmBrut >= rpmSeuilVert) ||
                   (role == 1 && rpmBrut >= rpmSeuilRouge) ||
                   (role == 2 && rpmBrut >= rpmSeuilBleu)) {
          leds[i] = col;
        }
      }
      continue;
    }

    // Voyants : allumés si actifs ; clignotent si l'option "Clignote" de la LED est cochée
    bool actif = false;
    switch (role) {
      case 3:  actif = clignotantGauche; break;
      case 4:  actif = clignotantDroit; break;
      case 5:  actif = (tempEau > seuilSurchauffe); break;
      case 6:  actif = etatAlerteHuile; break;
      case 7:  actif = wifiApActif; break;
      case 8:  actif = feuxActifs; break;               // feux de croisement
      case 9:  actif = (niveauEssence < 15.0f); break;
      case 11: actif = pleinsPharesActifs; break;       // feux de route
      default: break;
    }
    if (!actif) continue;
    bool phase = (role == 3 || role == 4) ? phaseCligno : phaseRapide;
    if (!clignoteLeds[i] || phase) leds[i] = col;
  }

  // Repérage depuis l'interface Web : seule la LED choisie clignote
  if (ledRepere >= 0) {
    if (millis() < ledRepereFin) {
      FastLED.clear();
      if ((millis() / 120) % 2 == 0) leds[ledRepere] = ledRepereCouleur;
    } else {
      ledRepere = -1;
    }
  }
  FastLED.show();
}

