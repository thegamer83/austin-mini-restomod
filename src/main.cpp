const int GEAR_H  = 230;   // hauteur du chiffre
const int GEAR_T  = 36;    // épaisseur des traits

void barreEpaisse(int x1, int y1, int x2, int y2, int w, uint16_t col) {
  float dx = (float)(x2 - x1), dy = (float)(y2 - y1);
  float L = sqrtf(dx * dx + dy * dy);
  if (L < 1.0f) return;
  float nx = -dy / L * (w / 2.0f), ny = dx / L * (w / 2.0f);
  int ax = x1 + (int)nx, ay = y1 + (int)ny;
  int bx = x1 - (int)nx, by = y1 - (int)ny;
  int ex = x2 - (int)nx, ey = y2 - (int)ny;
  int fx = x2 + (int)nx, fy = y2 + (int)ny;
  tft.fillTriangle(ax, ay, bx, by, ex, ey, col);
  tft.fillTriangle(ax, ay, ex, ey, fx, fy, col);
}

void dessinerRapportGros(int r, uint16_t col) {
  const int W = GEAR_W, H = GEAR_H, T = GEAR_T;
  const int x0 = GEAR_CX - W / 2;
  const int y0 = GEAR_CY - H / 2;
  const int xr = x0 + W - T;          // barre verticale de droite
  const int ym = y0 + H / 2 - T / 2;  // barre horizontale du milieu
  const int yb = y0 + H - T;          // barre horizontale du bas

  switch (r) {
    case 0:  // N : deux montants + diagonale
      tft.fillRect(x0, y0, T, H, col);
      tft.fillRect(xr, y0, T, H, col);
      barreEpaisse(x0 + T / 2, y0 + T / 2, xr + T / 2, y0 + H - T / 2, (T * 9) / 10, col);
      break;
    case 1:
      tft.fillRect(GEAR_CX - T / 2 + 14, y0, T, H, col);
      barreEpaisse(GEAR_CX + 14, y0 + T / 2, x0 + T / 2 + 6, y0 + 82, (T * 8) / 10, col);
      break;
    case 2:
      tft.fillRect(x0, y0, W, T, col);
      tft.fillRect(xr, y0, T, H / 2, col);
      tft.fillRect(x0, ym, W, T, col);
      tft.fillRect(x0, y0 + H / 2, T, H / 2, col);
      tft.fillRect(x0, yb, W, T, col);
      break;
    case 3:
      tft.fillRect(x0, y0, W, T, col);
      tft.fillRect(xr, y0, T, H, col);
      tft.fillRect(x0, ym, W, T, col);
      tft.fillRect(x0, yb, W, T, col);
      break;
    case 4:
      tft.fillRect(x0, y0, T, ym + T - y0, col);
      tft.fillRect(xr, y0, T, H, col);
      tft.fillRect(x0, ym, W, T, col);
      break;
    default:
      break;
  }
}

