bool trajetEnCours = false;
unsigned long trajetDebutMs = 0, trajetDernierMouvementMs = 0, trajetDernierSaveMs = 0;
double trajetDistKm = 0.0;
float trajetVmax = 0.0f, trajetEauMax = 0.0f, trajetEssenceDebut = 0.0f;
char trajetDate[12] = "?";
char trajetHeure[8] = "--:--";

String formaterTrajet(unsigned long dureeS, double dist, float vmax, float eauMax, float essDebut, float essFin,
                      const char* date, const char* heure) {
  float h = dureeS / 3600.0f;
  float vmoy = (h > 0.001f) ? (float)(dist / h) : 0.0f;
  char buf[160];
  snprintf(buf, sizeof(buf), "%s;%s;%lu;%.1f;%.0f;%.0f;%.0f;%.0f;%.0f",
           date, heure, (dureeS + 30) / 60, dist, vmax, vmoy, eauMax, essDebut, essFin);
  return String(buf);
}

// Sauvegarde du trajet en cours (la coupure du contact éteint l'ESP32 sans prévenir)
void sauvegarderTrajetEnCours() {
  preferences.begin("trajet", false);
  preferences.putBool("on", true);
  preferences.putUInt("dur", (trajetDernierMouvementMs - trajetDebutMs) / 1000);
  preferences.putFloat("dist", (float)trajetDistKm);
  preferences.putFloat("vmax", trajetVmax);
  preferences.putFloat("eau", trajetEauMax);
  preferences.putFloat("es0", trajetEssenceDebut);
  preferences.putFloat("es1", niveauEssence);
  preferences.putString("date", trajetDate);
  preferences.putString("heure", trajetHeure);
  preferences.end();
  trajetDernierSaveMs = millis();
}

// Au démarrage : un trajet interrompu par la coupure du contact est ajouté au journal
void recupererTrajetInterrompu() {
  preferences.begin("trajet", false);
  if (preferences.getBool("on", false)) {
    unsigned long dur = preferences.getUInt("dur", 0);
    float dist = preferences.getFloat("dist", 0.0f);
    float vmax = preferences.getFloat("vmax", 0.0f);
    float eau = preferences.getFloat("eau", 0.0f);
    float es0 = preferences.getFloat("es0", 0.0f);
    float es1 = preferences.getFloat("es1", 0.0f);
    String date = preferences.getString("date", "?");
    String heure = preferences.getString("heure", "--:--");
    if (dist >= 0.1f) ajouterLigneJournal(formaterTrajet(dur, dist, vmax, eau, es0, es1, date.c_str(), heure.c_str()));
    preferences.putBool("on", false);
  }
  preferences.end();
}

void demarrerTrajet() {
  trajetEnCours = true;
  trajetDebutMs = millis();
  trajetDernierMouvementMs = trajetDebutMs;
  trajetDernierSaveMs = trajetDebutMs;
  trajetDistKm = 0.0;
  trajetVmax = 0.0f;
  trajetEauMax = tempEau;
  trajetEssenceDebut = niveauEssence;
  if (gps.date.isValid() && gps.date.year() >= 2024)
    snprintf(trajetDate, sizeof(trajetDate), "%04d-%02d-%02d", gps.date.year(), gps.date.month(), gps.date.day());
  else
    snprintf(trajetDate, sizeof(trajetDate), "?");
  if (horlogeSynchro) {
    long sec = horlogeSecondes();
    snprintf(trajetHeure, sizeof(trajetHeure), "%02d:%02d", (int)(sec / 3600), (int)((sec / 60) % 60));
  } else {
    snprintf(trajetHeure, sizeof(trajetHeure), "--:--");
  }
}

// Fin normale : arrêt de plus de 5 minutes
void terminerTrajet() {
  if (trajetDistKm >= 0.1) {
    ajouterLigneJournal(formaterTrajet((trajetDernierMouvementMs - trajetDebutMs) / 1000, trajetDistKm, trajetVmax,
                                       trajetEauMax, trajetEssenceDebut, niveauEssence, trajetDate, trajetHeure));
  }
  preferences.begin("trajet", false);
  preferences.putBool("on", false);
  preferences.end();
  trajetEnCours = false;
}

void gererJournalTrajet() {
  static unsigned long dernier = 0;
  unsigned long maintenant = millis();
  if (maintenant - dernier < 1000) return;
  dernier = maintenant;

  float v = vitesseGpsKmph;
  if (!trajetEnCours) {
    if (v > 5.0f) demarrerTrajet();
    return;
  }
  trajetDistKm += v / 3600.0f;
  if (v > trajetVmax) trajetVmax = v;
  if (tempEau > trajetEauMax) trajetEauMax = tempEau;
  if (v > 3.0f) trajetDernierMouvementMs = maintenant;

  if (maintenant - trajetDernierSaveMs >= 30000) sauvegarderTrajetEnCours();
  if (maintenant - trajetDernierMouvementMs > 300000) terminerTrajet();
}

